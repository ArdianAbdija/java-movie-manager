    private void btnResetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResetActionPerformed
         int choice = JOptionPane.showConfirmDialog(
            this,
            "This will DELETE ALL movies and reload them from RSS.\nDo you want to continue?",
            "Confirm reset",
            JOptionPane.YES_NO_OPTION
    );

    if (choice != JOptionPane.YES_OPTION) {
        return;
    }

    new Thread(() -> {
        try {
            // 1. Delete all movies from database
            repository.deleteAllMovies();

            // 2. Delete image files from assets folder (except no_image.png)
            deleteAssetImages();

            // 3. Reload movies from RSS
            repository.createMovies(MovieParser.parse());

            // 4. Notify user (on EDT)
            SwingUtilities.invokeLater(() ->
                    JOptionPane.showMessageDialog(
                            this,
                            "Reset completed successfully.",
                            "Done",
                            JOptionPane.INFORMATION_MESSAGE
                    )
            );

        } catch (Exception ex) {
            SwingUtilities.invokeLater(() ->
                    JOptionPane.showMessageDialog(
                            this,
                            ex.getMessage(),
                            "Error",
                            JOptionPane.ERROR_MESSAGE
                    )
            );
        }
    }).start();
    }//GEN-LAST:event_btnResetActionPerformed


