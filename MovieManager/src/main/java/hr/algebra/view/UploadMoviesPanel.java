    private DefaultListModel<Movie> moviesModel;
    private Repository repository;

    private void init() {
        try {
            repository = RepositoryFactory.getRepository();
            moviesModel = new DefaultListModel<>();
            loadModel();
        } catch (Exception ex) {
            Logger.getLogger(UploadMoviesPanel.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Unrecoverable error", "Cannot initiate the form");
            System.exit(1);
        }
    }
    
    private void loadModel() throws Exception {
        List<Movie> movies = repository.selectMovies();
        
           java.awt.EventQueue.invokeLater(() -> {
    
        moviesModel.clear();
        movies.forEach(moviesModel::addElement);
        lsMovies.setModel(moviesModel);
        });
    }
    private void deleteAssetImages() throws Exception {
    Path assetsDir = Paths.get("assets");
    if (!Files.exists(assetsDir)) {
        return;
    }

    try (DirectoryStream<Path> stream = Files.newDirectoryStream(assetsDir)) {
        for (Path file : stream) {
            if (Files.isRegularFile(file)
                    && !file.getFileName().toString().equalsIgnoreCase("no_image.png")) {
                Files.deleteIfExists(file);
            }
        }
    }
}

        
