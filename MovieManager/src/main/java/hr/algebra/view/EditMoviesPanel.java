    private void enableImageDragAndDrop() {
    lbIcon.setTransferHandler(new TransferHandler() {

        @Override
        public boolean canImport(TransferSupport support) {
            if (!support.isDataFlavorSupported(DataFlavor.javaFileListFlavor)) {
                return false;
            }
            support.setDropAction(COPY);
            return true;
        }

        @Override
        @SuppressWarnings("unchecked")
        public boolean importData(TransferSupport support) {
            try {
                if (!canImport(support)) {
                    return false;
                }

                List<File> files = (List<File>) support.getTransferable()
                        .getTransferData(DataFlavor.javaFileListFlavor);

                if (files == null || files.isEmpty()) {
                    return false;
                }

                File file = files.get(0);

                String name = file.getName().toLowerCase();
                boolean isImage = name.endsWith(".png")
                        || name.endsWith(".jpg")
                        || name.endsWith(".jpeg")
                        || name.endsWith(".gif");

                if (!isImage) {
                    javax.swing.JOptionPane.showMessageDialog(
                            EditMoviesPanel.this,
                            "please drop an image file (png/jpg/jpeg/gif)",
                            "drag & drop",
                            javax.swing.JOptionPane.WARNING_MESSAGE
                    );
                    return false;
                }

                // ✅ store the file somewhere inside your project runtime (so it doesn’t depend on original location)
                // adjust folder if your project already uses a specific assets/images dir
                File dir = new File("assets");
                if (!dir.exists()) {
                    dir.mkdirs();
                }

                File dest = new File(dir, System.currentTimeMillis() + "_" + file.getName());
                Files.copy(file.toPath(), dest.toPath(), StandardCopyOption.REPLACE_EXISTING);

                // update UI like Choose Image does
                tfPicturePath.setText(dest.getAbsolutePath());

                // if you already have a method that sets the icon preview, call it here instead
                lbIcon.setIcon(new javax.swing.ImageIcon(dest.getAbsolutePath()));

                return true;

            } catch (Exception ex) {
                javax.swing.JOptionPane.showMessageDialog(
                        EditMoviesPanel.this,
                        "drop failed: " + ex.getMessage(),
                        "drag & drop",
                        javax.swing.JOptionPane.ERROR_MESSAGE
                );
                return false;
            }
        }
    });
}

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (!formValid()) {
            return;
        }
        try {
            String localPicturePath = uploadPicture();  
            Movie movie = new Movie(
                    tfTitle.getText().trim(),
                    tfLink.getText().trim(),
                    taDescription.getText().trim(),
                    localPicturePath,
                    LocalDateTime.parse(tfPublishedDate.getText().trim(), Movie.DATE_FORMATTER)
            );
            repository.createMovie(movie);
            moviesTableModel.setMovies(repository.selectMovies());

            clearForm();
        } catch (Exception ex) {
            Logger.getLogger(EditMoviesPanel.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Error", "Unable to create movie!");
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (selectedMovie == null) {
            MessageUtils.showInformationMessage("Wrong operation", "Please choose movie to update");
            return;
        }
        if (!formValid()) {
            return;
        }
        try {
            if (!tfPicturePath.getText().trim().equals(selectedMovie.getPicturePath())) {
                if (selectedMovie.getPicturePath() != null) {
                    Files.deleteIfExists(Paths.get(selectedMovie.getPicturePath()));
                }
                String localPicturePath = uploadPicture();
                selectedMovie.setPicturePath(localPicturePath);
            }

            selectedMovie.setTitle(tfTitle.getText().trim());
            selectedMovie.setLink(tfLink.getText().trim());
            selectedMovie.setDescription(taDescription.getText().trim());
            selectedMovie.setPublishedDate(LocalDateTime.parse(tfPublishedDate.getText().trim(), Movie.DATE_FORMATTER));

            repository.updateMovie(selectedMovie.getId(), selectedMovie);
            moviesTableModel.setMovies(repository.selectMovies());

            clearForm();
        } catch (Exception ex) {
            Logger.getLogger(EditMoviesPanel.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Error", "Unable to update movie!");
        }

    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (selectedMovie == null) {
            MessageUtils.showInformationMessage("Wrong operation", "Please choose movie to delete");
            return;
        }
        if (MessageUtils.showConfirmDialog(
                "Delete movie",
                "Do you really want to delete movie?")) {
            try {
                if (selectedMovie.getPicturePath() != null) {
                    Files.deleteIfExists(Paths.get(selectedMovie.getPicturePath()));
                }
                repository.deleteMovie(selectedMovie.getId());
                moviesTableModel.setMovies(repository.selectMovies());

                clearForm();
            } catch (Exception ex) {
                Logger.getLogger(EditMoviesPanel.class.getName()).log(Level.SEVERE, null, ex);
                MessageUtils.showErrorMessage("Error", "Unable to delete movie!");
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

