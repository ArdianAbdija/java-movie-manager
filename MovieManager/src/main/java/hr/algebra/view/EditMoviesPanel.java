    private void loadActors() throws Exception {
    cbActors.removeAllItems();
    for (Actor a : repository.selectActors()) {
        ((javax.swing.JComboBox) cbActors).addItem(a);


    }
}

private void loadActorsForMovie() throws Exception {
    DefaultListModel<Actor> model = new DefaultListModel<>();

    Movie movie = getSelectedMovie();
    if (movie != null) {
        for (Actor a : repository.selectActorsForMovie(movie.getId())) {
            model.addElement(a);
        }
    }
    
    lsMovieActors.setModel((javax.swing.ListModel) model);

}

