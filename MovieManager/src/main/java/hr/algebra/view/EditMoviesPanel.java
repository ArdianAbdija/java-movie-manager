    private void btnAddActorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActorActionPerformed
        // TODO add your handling code here:
         try {
        Movie movie = getSelectedMovie();
        Actor actor = (Actor) cbActors.getSelectedItem();
        if (movie == null || actor == null) return;

        repository.addActorToMovie(movie.getId(), actor.getId());
        loadActorsForMovie();
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, ex.getMessage(), "actors", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnAddActorActionPerformed

    private void btnRemoveActorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveActorActionPerformed
        // TODO add your handling code here:
         try {
        Movie movie = getSelectedMovie();
        Object selected = lsMovieActors.getSelectedValue();
        if (!(selected instanceof Actor)) return;

        Actor actor = (Actor) selected;

        repository.removeActorFromMovie(movie.getId(), actor.getId());
        loadActorsForMovie();
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, ex.getMessage(), "actors", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnRemoveActorActionPerformed


